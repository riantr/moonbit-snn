# gen_se_oracle.py -- a PyTorch autograd oracle for TARNet's post-MFA SE.
#
# WHY, and why it is small. The block oracle (verify/gen_block_oracle.py) covers
# Conv1DBlock including the paper's CTSE, because one instance of that code is
# every block in the network. What an independent reference still does not cover
# is the OTHER squeeze-excitation: `mfa_se`, the plain one the MFA applies after
# its 1x1 convolution, as opposed to CTSE's three-path channel-time gate. It is
# used once, so its coverage matters less than CTSE's, but it was still checked
# only against central differences of its own forward -- the check that cannot
# see a forward that is wrong in a self-consistent way.
#
# Transcribed from the reference's `SEModule` in
# `_build/tarnet_ref/tarnet/models/tarnet.py`:
#
#     nn.Sequential(
#         nn.AdaptiveAvgPool1d(1),
#         nn.Conv1d(channels, bottleneck, 1), nn.ReLU(),
#         nn.Conv1d(bottleneck, channels, 1), nn.Sigmoid(),
#     )
#     forward: x * weights
#
# The parameters come out of `tarnet_flatten` at a known offset, so the oracle
# is built from the same numbers the MoonBit side uses rather than from a second
# RNG.
#
# Run:  python verify/gen_se_oracle.py <block_export.log>

import io
import os
import sys

import numpy as np
import torch
import torch.nn.functional as F

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from gen_block_oracle import parse  # noqa: E402

N, C, T = 3, 8, 6
BNK = 32                     # max(32, fuse_out // 4) with fuse_out = 8
STACKS_END = 2313            # header(68) + 5 blocks(449)
MFA_W = C * 3 * 8            # fuse_out * 3 * bn_chan
MFA_B = C
SE_OFFSET = STACKS_END + MFA_W + MFA_B      # 2513
SE_LEN = BNK * C + BNK + C * BNK + C        # 552


class SE(torch.nn.Module):
    def __init__(self, c, bnk, p):
        super().__init__()
        self.fc1 = torch.nn.Conv1d(c, bnk, 1, bias=True)
        self.fc2 = torch.nn.Conv1d(bnk, c, 1, bias=True)
        k = 0
        self.fc1.weight.data = torch.tensor(
            p[k:k + bnk * c], dtype=torch.float32).view(bnk, c, 1)
        k += bnk * c
        self.fc1.bias.data = torch.tensor(p[k:k + bnk], dtype=torch.float32)
        k += bnk
        self.fc2.weight.data = torch.tensor(
            p[k:k + c * bnk], dtype=torch.float32).view(c, bnk, 1)
        k += c * bnk
        self.fc2.bias.data = torch.tensor(p[k:k + c], dtype=torch.float32)
        k += c
        assert k == len(p), "SE slice %d != %d" % (k, len(p))

    def forward(self, x):
        u = F.adaptive_avg_pool1d(x, 1)          # (B, C, 1)
        h = F.relu(self.fc1(u))                  # (B, BNK, 1)
        w = torch.sigmoid(self.fc2(h))           # (B, C, 1)
        return x * w

    def flat_grad(self):
        out = []
        out += list(self.fc1.weight.grad.reshape(-1))
        out += list(self.fc1.bias.grad)
        out += list(self.fc2.weight.grad.reshape(-1))
        out += list(self.fc2.bias.grad)
        return np.array(out, dtype=np.float32)


def fixture(seed):
    x = np.zeros((N, C, T), dtype=np.float32)
    for b in range(N):
        for c in range(C):
            base = 0.5 * c - 2.0
            scale = 0.3 + 0.2 * c
            for ti in range(T):
                h = ((b * T + ti) * 37 + c * 101 + seed) % 71 - 35
                x[b, c, ti] = base + scale * h / 35.0
    return torch.tensor(x)


def fmt(vals, per_line=6):
    def lit(v):
        s = repr(float(v))
        if "." not in s and "e" not in s and "E" not in s:
            s += ".0"
        return s + "F"
    flat = list(np.asarray(vals).reshape(-1))
    out, line = [], []
    for i, v in enumerate(flat):
        line.append(lit(v))
        if len(line) == per_line or i == len(flat) - 1:
            out.append("  " + ", ".join(line))
            line = []
    return "[\n" + ",\n".join(out) + ",\n]"


def main():
    params = parse(sys.argv[1])["params"]
    print("total params %d, SE at [%d, %d) = %d values"
          % (len(params), SE_OFFSET, SE_OFFSET + SE_LEN, SE_LEN))
    assert len(params) == 3573
    se_params = params[SE_OFFSET:SE_OFFSET + SE_LEN]

    x = fixture(0).requires_grad_(True)
    d_out = fixture(500)
    se = SE(C, BNK, se_params)
    y = se(x)
    (y * d_out).sum().backward()
    dp = se.flat_grad()

    print("out absmax %.6f   dx absmax %.6f   dparam absmax %.6f"
          % (y.abs().max(), x.grad.abs().max(), np.abs(dp).max()))

    src = f'''// GENERATED by verify/gen_se_oracle.py from PyTorch {torch.__version__}.
// Do not hand-edit: the gate that reads these compares against them.
//
// A PyTorch autograd reference for the post-MFA squeeze-excitation, transcribed
// from the reference's SEModule in
// `_build/tarnet_ref/tarnet/models/tarnet.py` rather than from this port. This
// is the PLAIN SE the MFA applies after its 1x1 convolution, and not the CTSE
// the blocks carry -- CTSE is covered by verify/gen_block_oracle.py, and
// conflating the two would check neither properly.
//
// It is checked against a finite difference of its own forward nowhere: that
// comparison cannot see a forward which is wrong in a self-consistent way,
// which is the failure this layer is most likely to have (the pooling axis,
// and whether the gate is applied to every frame or only the pooled one).

///|
///|```text
///|SE_N / SE_C / SE_T / SE_BOTTLENECK
///|"""

///|
///|```text
///|SE_N
///|"""

pub const SE_N : Int = {N}

///|
///|```text
///|SE_C
///|"""

pub const SE_C : Int = {C}

///|
///|```text
///|SE_T
///|"""

pub const SE_T : Int = {T}

///|
///|```text
///|SE_BOTTLENECK : max(32, fuse_out // 4) with fuse_out = 8
///|"""

pub const SE_BOTTLENECK : Int = {BNK}

///|
///|```text
///|se_out_golden : SE forward under autograd
///|"""

pub let se_out_golden : Array[Float] = {fmt(y.detach().numpy())}

///|
///|```text
///|se_dx_golden : d(sum(out*d_out))/d x
///|"""

pub let se_dx_golden : Array[Float] = {fmt(x.grad.numpy())}

///|
///|```text
///|se_dp_golden : the {SE_LEN} parameter gradients, w1/b1/w2/b2 in SeParam order
///|"""

pub let se_dp_golden : Array[Float] = {fmt(dp)}
'''
    out = os.path.join(ROOT, "mbt", "tests", "wave2", "se_oracle_golden.mbt")
    with io.open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src)
    print("wrote %s" % out)


if __name__ == "__main__":
    main()
